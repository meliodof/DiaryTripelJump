/**
 * Шаг подсказки: что подсветить ([target]; null — без подсветки) и что о нём сказать.
 * [tap] — пользователь нажимает подсвеченную кнопку, и обучение само переходит к открывшемуся окну.
 */
data class CoachStep(val target: String?, val title: String, val text: String, val tap: Boolean = false)

/** Шаг обучения вместе с разделом: по разделу понятно, на каком экране и в каком окне его показывать. */
data class TourStep(val topic: HelpTopic, val step: CoachStep) {
    val route: String get() = topic.route
}

